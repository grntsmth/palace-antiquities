#!/usr/bin/env python3
from __future__ import annotations
"""Build this Nexo pack from the art repo's inventory.

    python3 -I tools/convert.py --art /path/to/minecraftassets [--dry-run]

Reads <art>/assets.yml and ships every entry whose `status` is `plugin`:

  model-json in dings / furniture / stations / calligraphy  -> furniture item (Mechanics.furniture)
  model-json in blocks                                      -> NOTEBLOCK custom block with that model
  texture in blocks                                         -> NOTEBLOCK cube_all block (cube_column when a *_top sibling exists)
  texture in items / armor                                  -> plain item with that texture
  texture in dings / npc / mobs                             -> copied only (model dependency or not a Nexo thing)
  anything else (bbmodel, geo, animation, jem, misc)        -> skipped, listed in the report

Texture refs inside models are rewritten to `<ns>:block/...` (repo textures) or `minecraft:block/...`
(vanilla stems). A model with a ref that resolves to neither is REFUSED, not shipped.

Generated files: items/<group>.yml and everything under pack/assets/<ns>/. They are rewritten on every run.
Hand adjustments go in overrides/<item_id>.yml and are deep-merged over the generated entry.
NOTEBLOCK custom_variation numbers are pinned in ledger.yml and never reassigned.
"""
import argparse
import json
import math
import shutil
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

FURNITURE_GROUPS = {"dings", "furniture", "stations", "calligraphy"}
COPY_ONLY_GROUPS = {"dings", "npc", "mobs"}
ITEM_GROUPS = {"items", "armor"}
VANILLA = {
    "bamboo_planks", "campfire_fire", "campfire_log", "campfire_log_lit", "coal_block", "copper_block",
    "dark_oak_planks", "diamond_block", "emerald_block", "gold_block", "hay_block_side", "iron_block",
    "lava_flow", "lava_still", "mud_bricks", "netherite_block", "packed_mud", "polished_blackstone",
    "raw_gold_block", "red_wool", "spruce_planks", "stripped_dark_oak_log", "terracotta", "white_wool",
    "red_candle", "red_candle_lit", "water_still",
}
GENERATED_HEADER = "# GENERATED by tools/convert.py from the art repo inventory. Do not edit; use overrides/<id>.yml.\n"


def title(stem: str) -> str:
    return " ".join(w.capitalize() for w in stem.split("_"))


def item_id(rel: str) -> str:
    stem = Path(rel).stem
    return stem[6:] if stem.startswith("model_") else stem


def deep_merge(base: dict, over: dict) -> dict:
    out = dict(base)
    for k, v in over.items():
        out[k] = deep_merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def png_size(path: Path):
    import struct
    with path.open("rb") as fh:
        head = fh.read(24)
    return struct.unpack(">II", head[16:24]) if head[:8] == b"\x89PNG\r\n\x1a\n" else (0, 0)


class Converter:
    def __init__(self, art: Path, out: Path, ns: str, dry: bool):
        self.art, self.out, self.ns, self.dry = art, out, ns, dry
        self.assets = (yaml.safe_load((art / "assets.yml").read_text(encoding="utf-8")) or {}).get("assets") or {}
        self.png_by_stem = {}
        for rel, e in self.assets.items():
            if e.get("kind") == "texture" and not e.get("missing"):
                self.png_by_stem.setdefault(Path(rel).stem, rel)
        self.items = defaultdict(dict)       # group file -> {id: entry}
        self.copied = {}                     # art rel -> pack rel
        self.skipped = []                    # (rel, reason)
        self.refused = []                    # (rel, [missing refs])
        self.ledger_path = out / "ledger.yml"
        self.ledger = yaml.safe_load(self.ledger_path.read_text(encoding="utf-8")) if self.ledger_path.exists() else {}
        self.ledger.setdefault("noteblock", {})
        self.overrides = {p.stem: yaml.safe_load(p.read_text(encoding="utf-8")) or {} for p in (out / "overrides").glob("*.yml")}

    # ---- paths -------------------------------------------------------------
    def tex_pack_path(self, art_rel: str) -> str:
        """textures/block/dings/x.png -> block/dings/x  (namespace-relative, no extension)"""
        p = Path(art_rel)
        return p.relative_to("textures").with_suffix("").as_posix()

    def model_pack_path(self, art_rel: str) -> str:
        """models/block/dings/x.json -> block/dings/x"""
        return Path(art_rel).relative_to("models").with_suffix("").as_posix()

    def copy_texture(self, art_rel: str):
        dest = self.out / "pack/assets" / self.ns / "textures" / Path(art_rel).relative_to("textures")
        self.copied[art_rel] = dest.relative_to(self.out).as_posix()
        if not self.dry:
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(self.art / art_rel, dest)

    def resolve_ref(self, ref: str):
        if ref.startswith("#"):
            return ref, None
        if ref.startswith("minecraft:"):
            return ref, None
        stem = ref.split(":")[-1].split("/")[-1]
        if stem in self.png_by_stem:
            art_rel = self.png_by_stem[stem]
            return f"{self.ns}:{self.tex_pack_path(art_rel)}", art_rel
        if stem in VANILLA:
            return f"minecraft:block/{stem}", None
        return None, None

    # ---- variation ledger ----------------------------------------------------
    def variation_for(self, iid: str) -> int:
        led = self.ledger["noteblock"]
        if iid not in led:
            led[iid] = max(led.values(), default=0) + 1
        return led[iid]

    # ---- model handling -------------------------------------------------------
    def ship_model(self, art_rel: str):
        """Rewrite refs, copy textures, write model. Returns (pack model path, element bbox) or None."""
        model = json.loads((self.art / art_rel).read_text(encoding="utf-8"))
        missing, deps = [], []
        new_tex = {}
        for key, ref in (model.get("textures") or {}).items():
            if not isinstance(ref, str):
                continue
            resolved, dep = self.resolve_ref(ref)
            if resolved is None:
                missing.append(ref)
            else:
                new_tex[key] = resolved
                if dep:
                    deps.append(dep)
        if missing:
            self.refused.append((art_rel, sorted(set(missing))))
            return None
        model["textures"] = new_tex
        model.pop("groups", None)  # Blockbench outliner metadata, not read by the game
        for dep in deps:
            self.copy_texture(dep)
        pack_path = self.model_pack_path(art_rel)
        dest = self.out / "pack/assets" / self.ns / "models" / (pack_path + ".json")
        if not self.dry:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(json.dumps(model, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        return pack_path, self.bbox(model)

    @staticmethod
    def bbox(model: dict):
        lo = [math.inf] * 3
        hi = [-math.inf] * 3
        for el in model.get("elements") or []:
            for i in range(3):
                lo[i] = min(lo[i], el["from"][i], el["to"][i])
                hi[i] = max(hi[i], el["from"][i], el["to"][i])
        return None if math.isinf(lo[0]) else (lo, hi)

    @staticmethod
    def barriers(bb) -> list:
        """Block offsets covered by the model's bounding box (model units: 16 per block, base block = 0..16)."""
        if bb is None:
            return ["0,0,0"]
        lo, hi = bb
        rng = []
        for i in range(3):
            a = math.floor(lo[i] / 16 + 1e-6)
            b = math.ceil(hi[i] / 16 - 1e-6) - 1
            rng.append(range(min(a, 0) if i == 1 else a, max(b, 0) + 1))
        # Y never goes below the base block; a model that dips below 0 still sits on the floor.
        rng[1] = range(0, max(rng[1].stop, 1))
        cells = [f"{x},{y},{z}" for y in rng[1] for x in rng[0] for z in rng[2]]
        return cells or ["0,0,0"]

    # ---- entry builders --------------------------------------------------------
    def furniture_entry(self, iid: str, pack_model: str, bb, notes: str) -> dict:
        entry = {
            "itemname": f"<!i>{title(iid)}",
            "material": "PAPER",
            "Pack": {"model": f"{self.ns}:{pack_model}"},
            "Mechanics": {"furniture": {
                "properties": {"display_transform": "NONE"},
                "hitbox": {"barriers": self.barriers(bb)},
                "rotatable": True,
                "restricted_rotation": "STRICT",
            }},
        }
        if iid.endswith(("_on", "_lit")):
            entry["Mechanics"]["furniture"]["lights"] = {"light": "0,1,0 10"}
        return entry

    def noteblock_model_entry(self, iid: str, pack_model: str) -> dict:
        return {
            "itemname": f"<!i>{title(iid)}",
            "material": "PAPER",
            "Pack": {"model": f"{self.ns}:{pack_model}"},
            "Mechanics": {"custom_block": {"type": "NOTEBLOCK", "custom_variation": self.variation_for(iid),
                                           "model": f"{self.ns}:{pack_model}", "hardness": 2}},
        }

    def noteblock_texture_entry(self, iid: str, art_rel: str, top_rel=None) -> dict:
        side = f"{self.ns}:{self.tex_pack_path(art_rel)}"
        pack = {"parent_model": "block/cube_all", "texture": side}
        if top_rel:
            pack = {"parent_model": "block/cube_column", "textures": {"side": side, "end": f"{self.ns}:{self.tex_pack_path(top_rel)}"}}
        return {
            "itemname": f"<!i>{title(iid)}",
            "material": "PAPER",
            "Pack": pack,
            "Mechanics": {"custom_block": {"type": "NOTEBLOCK", "custom_variation": self.variation_for(iid), "hardness": 2}},
        }

    def item_entry(self, iid: str, art_rel: str) -> dict:
        return {"itemname": f"<!i>{title(iid)}", "material": "PAPER",
                "Pack": {"parent_model": "item/generated", "texture": f"{self.ns}:{self.tex_pack_path(art_rel)}"}}

    # ---- main --------------------------------------------------------------------
    def run(self):
        chosen = {rel: e for rel, e in self.assets.items() if e.get("status") == "plugin" and not e.get("missing")}
        stems_chosen = {Path(r).stem for r in chosen}
        for rel, e in sorted(chosen.items()):
            kind, group, notes = e.get("kind"), e.get("group"), e.get("notes") or ""
            iid = item_id(rel)
            if kind == "model-json":
                shipped = self.ship_model(rel)
                if shipped is None:
                    continue
                pack_model, bb = shipped
                if group in FURNITURE_GROUPS:
                    self.add("furniture" if group != "dings" else "dings", iid, self.furniture_entry(iid, pack_model, bb, notes))
                elif group == "blocks":
                    self.add("blocks", iid, self.noteblock_model_entry(iid, pack_model))
                else:
                    self.add("items", iid, {"itemname": f"<!i>{title(iid)}", "material": "PAPER",
                                            "Pack": {"model": f"{self.ns}:{pack_model}"}})
            elif kind == "texture":
                if group == "blocks":
                    stem = Path(rel).stem
                    if stem.endswith("_top") and stem[:-4] in stems_chosen:
                        self.copy_texture(rel)
                        self.skipped.append((rel, f"merged into {stem[:-4]} as cube_column end"))
                        continue
                    top = self.png_by_stem.get(stem + "_top")
                    top_rel = top if top and Path(top).stem in stems_chosen else None
                    self.copy_texture(rel)
                    if top_rel:
                        self.copy_texture(top_rel)
                    self.add("blocks", iid, self.noteblock_texture_entry(iid, rel, top_rel))
                elif group in ITEM_GROUPS:
                    self.copy_texture(rel)
                    self.add("items", iid, self.item_entry(iid, rel))
                elif group in COPY_ONLY_GROUPS:
                    self.copy_texture(rel)
                    self.skipped.append((rel, "copied only: texture in a group that has no standalone Nexo item"))
                else:
                    self.skipped.append((rel, f"no rule for texture group {group}"))
            else:
                self.skipped.append((rel, f"{kind} is not shippable (bbmodel sources, geckolib, CEM, misc)"))
        self.write()
        self.report()
        return 1 if self.refused else 0

    def add(self, file: str, iid: str, entry: dict):
        if iid in self.overrides:
            entry = deep_merge(entry, self.overrides[iid])
        if any(iid in d for d in self.items.values()):
            self.skipped.append((iid, "duplicate item id, second occurrence dropped"))
            return
        self.items[file][iid] = entry

    def write(self):
        if self.dry:
            return
        gen_assets = self.out / "pack/assets" / self.ns
        # pack/assets/<ns> is fully generated; wipe then rebuild (textures/models were already written above into
        # the fresh tree because copy/ship ran before write -> so wipe happens at construction time instead)
        items_dir = self.out / "items"
        items_dir.mkdir(exist_ok=True)
        for old in items_dir.glob("*.yml"):
            if old.read_text(encoding="utf-8").startswith(GENERATED_HEADER):
                old.unlink()
        for file, entries in self.items.items():
            (items_dir / f"{file}.yml").write_text(
                GENERATED_HEADER + yaml.safe_dump(entries, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
        self.ledger_path.write_text("# custom_variation pins. Never edit or reuse a number once a block has been placed.\n"
                                    + yaml.safe_dump(self.ledger, sort_keys=True), encoding="utf-8")

    def report(self):
        n_items = sum(len(v) for v in self.items.values())
        print(f"{'DRY RUN: ' if self.dry else ''}shipped {n_items} items in {len(self.items)} files; "
              f"{len(self.copied)} textures copied; {len(self.refused)} models refused; {len(self.skipped)} skipped")
        for file, entries in sorted(self.items.items()):
            print(f"  items/{file}.yml: {', '.join(entries)}")
        if self.refused:
            print("REFUSED (unresolved texture refs):")
            for rel, miss in self.refused:
                print(f"  {rel}: {', '.join(miss)}")
        if self.skipped:
            print("skipped:")
            for rel, why in self.skipped:
                print(f"  {rel}: {why}")
        sizes = []
        total = 0
        for art_rel in self.copied:
            p = self.art / art_rel
            b = p.stat().st_size
            total += b
            w, h = png_size(p)
            sizes.append((b, w, h, art_rel))
        if sizes:
            print(f"pack textures: {len(sizes)} files, {total/1024:.0f} KiB")
            big = [s for s in sizes if s[1] >= 256 or s[2] >= 256]
            if big:
                print(f"  256px+ textures ({len(big)}), largest first:")
                for b, w, h, rel in sorted(big, reverse=True):
                    print(f"    {b/1024:6.0f} KiB  {w}x{h}  {rel}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--art", type=Path, required=True, help="path to the minecraftassets clone (must contain assets.yml)")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent.parent, help="pack repo root")
    ap.add_argument("--namespace", default="palace")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    if not (a.art / "assets.yml").exists():
        ap.error(f"{a.art} has no assets.yml; run tools/inventory.py scan there first")
    gen = a.out / "pack/assets" / a.namespace
    if gen.exists() and not a.dry_run:
        shutil.rmtree(gen)
    return Converter(a.art.resolve(), a.out.resolve(), a.namespace, a.dry_run).run()


if __name__ == "__main__":
    sys.exit(main())
